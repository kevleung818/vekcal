export function getCategoryInterpretation(hexagramNumber, category, language) {
  if (!Number.isInteger(hexagramNumber) || hexagramNumber < 1 || hexagramNumber > 64) {
    throw new RangeError("Hexagram number must be from 1 to 64.");
  }
  if (!INTERPRETATION_CATEGORIES.includes(category)) {
    throw new TypeError("Choose a supported interpretation category.");
  }
  const reading = INTERPRETATIONS[language]?.[hexagramNumber - 1]?.[category];
  if (!reading) throw new TypeError("Choose a supported interpretation language.");
  return reading;
}
